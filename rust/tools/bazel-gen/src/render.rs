//! The text of the BUILD files.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use crate::model::{Applies, Dep, Package, Target, Workspace};

const GENERATED: &str = "# @generated by rust/tools/bazel-gen from the Cargo manifests; do not edit. Regenerate with `bazel run //:gazelle` (the `layout_test` of bazel-gen fails when a file is stale).\n";

/// Files outside a package that a test reads at run time (a path under the repository root, which Cargo gives as
/// `CARGO_MANIFEST_DIR/../../../...`): (package, test) -> the root filegroup holding them.
const EXTRA_DATA: &[(&str, &str, &str)] = &[
    ("euhedral-inference-settings", "example", "//:config_example"),
    ("euhedral-inference-bench", "config", "//:benchmark_configs"),
    ("euhedral-inference-quantization", "npy_npz", "//:gptq_fixture"),
];

/// A BUILD attribute value.
enum Value {
    Text(String),
    List(Vec<String>),
    Map(Vec<(String, String)>),
    /// Starlark as written (a glob, a select, a sum).
    Raw(String),
}

fn quote(text: &str) -> String {
    format!("\"{text}\"")
}

struct Rule {
    kind: &'static str,
    attrs: BTreeMap<&'static str, Value>,
}

impl Rule {
    fn new(kind: &'static str, name: &str) -> Self {
        let mut attrs = BTreeMap::new();
        attrs.insert("name", Value::Text(name.to_owned()));
        Self { kind, attrs }
    }

    fn set(&mut self, key: &'static str, value: Value) -> &mut Self {
        self.attrs.insert(key, value);
        self
    }

    fn text(&mut self, key: &'static str, value: &str) -> &mut Self {
        self.set(key, Value::Text(value.to_owned()))
    }

    fn list(&mut self, key: &'static str, values: Vec<String>) -> &mut Self {
        if !values.is_empty() {
            self.set(key, Value::List(values));
        }
        self
    }

    fn render(&self) -> String {
        let mut out = format!("{}(\n", self.kind);
        if let Some(name) = self.attrs.get("name") {
            let _ = writeln!(out, "    name = {},", value(name, 1));
        }
        for (key, attr) in &self.attrs {
            if *key != "name" {
                let _ = writeln!(out, "    {key} = {},", value(attr, 1));
            }
        }
        out.push_str(")\n");
        out
    }
}

fn value(attr: &Value, depth: usize) -> String {
    let pad = "    ".repeat(depth + 1);
    let close = "    ".repeat(depth);
    match attr {
        Value::Text(text) => quote(text),
        Value::List(items) if items.len() == 1 => format!("[{}]", quote(&items[0])),
        Value::List(items) => {
            let mut out = String::from("[\n");
            for item in items {
                let _ = writeln!(out, "{pad}{},", quote(item));
            }
            format!("{out}{close}]")
        }
        Value::Map(entries) => {
            let mut out = String::from("{\n");
            for (key, item) in entries {
                let _ = writeln!(out, "{pad}{}: {},", quote(key), quote(item));
            }
            format!("{out}{close}}}")
        }
        Value::Raw(text) => text.replace('\n', &format!("\n{close}")),
    }
}

fn glob(include: &[&str], exclude: &[&str], allow_empty: bool) -> Value {
    let mut out = String::from("glob(\n    [\n");
    for item in include {
        let _ = writeln!(out, "        {},", quote(item));
    }
    out.push_str("    ],\n");
    if !exclude.is_empty() {
        out.push_str("    exclude = [");
        out.push_str(&exclude.iter().map(|item| quote(item)).collect::<Vec<_>>().join(", "));
        out.push_str("],\n");
    }
    if allow_empty {
        out.push_str("    allow_empty = True,\n");
    }
    out.push(')');
    Value::Raw(out)
}

/// `value` with the labels appended (`glob(...) + [...]`).
fn plus(value: Value, labels: &[String]) -> Value {
    if labels.is_empty() {
        return value;
    }
    let text = match value {
        Value::Raw(text) => text,
        _ => String::new(),
    };
    Value::Raw(format!("{text} + {}", labels_at(labels, 0)))
}

/// The package that owns `path` (a path from the repository root): its directory and the path inside it. Files under
/// no package belong to the root package.
fn owner<'a>(workspace: &'a Workspace, path: &'a str) -> (&'a str, &'a str) {
    workspace
        .packages
        .iter()
        .filter_map(|package| {
            Some((
                package.dir.as_str(),
                path.strip_prefix(package.dir.as_str())?.strip_prefix('/')?,
            ))
        })
        .max_by_key(|(dir, _)| dir.len())
        .unwrap_or(("", path))
}

fn outside_label(workspace: &Workspace, path: &str) -> String {
    let (dir, inside) = owner(workspace, path);
    format!("//{dir}:{inside}")
}

/// A list of labels written at `indent` levels, closing bracket included.
fn labels_at(labels: &[String], indent: usize) -> String {
    if labels.is_empty() {
        return "[]".to_owned();
    }
    let pad = "    ".repeat(indent + 1);
    let mut out = String::from("[\n");
    for label in labels {
        let _ = writeln!(out, "{pad}{},", quote(label));
    }
    format!("{out}{}]", "    ".repeat(indent))
}

/// A dependency list: the labels that always apply (`lib` first, if any), then one `select` per operating-system family.
fn deps(lib: Option<&str>, deps: &[&Dep]) -> Option<Value> {
    let pick = |applies: Applies| -> Vec<String> {
        let labels: BTreeSet<&str> = deps
            .iter()
            .filter(|dep| dep.applies == applies)
            .map(|dep| dep.label.as_str())
            .collect();
        labels.into_iter().map(str::to_owned).collect()
    };
    let mut always = pick(Applies::Always);
    if let Some(lib) = lib {
        always.insert(0, lib.to_owned());
    }
    let unix = pick(Applies::Unix);
    let windows = pick(Applies::Windows);
    let mut parts = Vec::new();
    if !always.is_empty() {
        parts.push(labels_at(&always, 0));
    }
    if !unix.is_empty() {
        parts.push(format!(
            "select({{\n    \"@platforms//os:windows\": [],\n    \"//conditions:default\": {},\n}})",
            labels_at(&unix, 1)
        ));
    }
    if !windows.is_empty() {
        parts.push(format!(
            "select({{\n    \"@platforms//os:windows\": {},\n    \"//conditions:default\": [],\n}})",
            labels_at(&windows, 1)
        ));
    }
    if parts.is_empty() {
        return None;
    }
    Some(Value::Raw(parts.join(" + ")))
}

fn identifier(name: &str) -> String {
    name.replace('-', "_")
}

/// Every file the generator writes, by path from the repository root.
pub fn files(workspace: &Workspace) -> Result<BTreeMap<String, String>, String> {
    let mut files = BTreeMap::new();
    // What the layout test reads: every manifest and BUILD file, and the files the pin check reads.
    let mut layout_data: Vec<String> = vec![
        "//:BUILD.bazel".to_owned(),
        "//:MODULE.bazel".to_owned(),
        "//:mise.toml".to_owned(),
        "//rust:BUILD.bazel".to_owned(),
        "//rust:Cargo.lock".to_owned(),
        "//rust:Cargo.toml".to_owned(),
        "//rust:rust-toolchain.toml".to_owned(),
    ];
    for package in &workspace.packages {
        layout_data.push(format!("//{}:BUILD.bazel", package.dir));
        layout_data.push(format!("//{}:Cargo.toml", package.dir));
    }
    layout_data.sort();
    for package in &workspace.packages {
        files.insert(
            format!("{}/BUILD.bazel", package.dir),
            package_file(workspace, package, &layout_data)?,
        );
    }
    files.insert("rust/BUILD.bazel".to_owned(), rust_file());
    files.insert("BUILD.bazel".to_owned(), root_file(workspace)?);
    Ok(files)
}

fn rust_file() -> String {
    format!(
        "{GENERATED}\n# The files crate_universe reads, and the ones the layout test checks.\nexports_files([\n    \"BUILD.bazel\",\n    \"Cargo.lock\",\n    \"Cargo.toml\",\n    \"rust-toolchain.toml\",\n])\n"
    )
}

fn root_file(workspace: &Workspace) -> Result<String, String> {
    let mut out = format!("{GENERATED}\n");
    out.push_str("# `bazel run //:gazelle` writes the BUILD files; `-- -mode=diff` fails and names the stale ones.\n");
    let mut rule = Rule::new("alias", "gazelle");
    rule.text("actual", "//rust/tools/bazel-gen:bazel-gen")
        .list("visibility", vec!["//visibility:public".to_owned()]);
    out.push_str(&rule.render());
    out.push('\n');
    let outside: BTreeSet<&str> = workspace
        .packages
        .iter()
        .flat_map(|package| package.outside.iter())
        .map(String::as_str)
        .filter(|path| owner(workspace, path).0.is_empty())
        .collect();
    if !outside.is_empty() {
        out.push_str("# Files the crates include with include_str! from outside their package.\n");
        let list: Vec<String> = outside.into_iter().map(str::to_owned).collect();
        out.push_str(&format!("exports_files({})\n", labels_at(&list, 0)));
    }
    out.push_str("\n# The files the layout test of bazel-gen reads.\nexports_files([\"BUILD.bazel\", \"MODULE.bazel\", \"mise.toml\"])\n");
    out.push_str("\n# Files outside rust/ that the tests of rust/ read.\n");
    for (name, include) in [
        ("config_example", "config/euhedral.example.yaml"),
        ("benchmark_configs", "benchmark/configs/**"),
        ("gptq_fixture", "quantization/src/test/resources/gptq-fixture/**"),
    ] {
        let mut rule = Rule::new("filegroup", name);
        rule.set("srcs", glob(&[include], &[], false))
            .list("visibility", vec!["//visibility:public".to_owned()]);
        out.push('\n');
        out.push_str(&rule.render());
    }
    Ok(out)
}

fn package_file(workspace: &Workspace, package: &Package, layout_data: &[String]) -> Result<String, String> {
    let mut names = BTreeSet::new();
    let mut claim = |name: &str| -> Result<(), String> {
        if names.insert(name.to_owned()) {
            Ok(())
        } else {
            Err(format!("{}: two targets are named {name}", package.name))
        }
    };
    let normal: Vec<&Dep> = package.deps.iter().filter(|dep| !dep.dev).collect();
    let dev: Vec<&Dep> = package.deps.iter().filter(|dep| dep.dev).collect();
    let all: Vec<&Dep> = package.deps.iter().collect();
    let lib_label = package.lib.as_ref().map(|_| format!(":{}", package.lib_name()));

    let lib_dep = lib_label.as_deref();

    let mut rules: Vec<(Option<String>, Rule)> = Vec::new();
    let common = |rule: &mut Rule| {
        rule.text("edition", &package.edition).text("version", &package.version);
        rule.list("crate_features", package.features.clone());
    };
    let runtime_env = |extra: Vec<(String, String)>| -> Value {
        let mut entries = vec![
            ("CARGO_MANIFEST_DIR".to_owned(), package.dir.clone()),
            ("CARGO_TARGET_TMPDIR".to_owned(), "unused-under-bazel".to_owned()),
        ];
        entries.extend(extra);
        entries.sort();
        Value::Map(entries)
    };
    let outside_labels: Vec<String> = package
        .outside
        .iter()
        .map(|path| outside_label(workspace, path))
        .collect();
    let data_files = glob(
        &["tests/**", "src/**", "Cargo.toml", "README.md"],
        &["tests/**/*.rs", "src/**/*.rs"],
        true,
    );
    let data_files_text = match &data_files {
        Value::Raw(text) => text.clone(),
        _ => String::new(),
    };

    if let Some(lib) = &package.lib {
        claim(&package.lib_name())?;
        let mut rule = Rule::new("rust_library", &package.lib_name());
        common(&mut rule);
        rule.text("crate_name", &package.lib_name())
            .text("crate_root", &lib.root)
            .set("srcs", glob(&["src/**/*.rs"], &[], false))
            .set(
                "compile_data",
                plus(glob(&["README.md", "src/**"], &["src/**/*.rs"], true), &outside_labels),
            )
            .list("visibility", vec!["//visibility:public".to_owned()]);
        if let Some(found) = deps(None, &normal) {
            rule.set("deps", found);
        }
        rules.push((Some("The library.".to_owned()), rule));

        claim("unit_test")?;
        let mut rule = Rule::new("rust_test", "unit_test");
        common(&mut rule);
        rule.text("crate", &format!(":{}", package.lib_name()));
        if let Some(found) = deps(None, &dev) {
            rule.set("deps", found);
        }
        rules.push((Some("The library's unit tests (#[cfg(test)]).".to_owned()), rule));

        claim("doc_test")?;
        let mut rule = Rule::new("rust_doc_test", "doc_test");
        rule.text("crate", &format!(":{}", package.lib_name()));
        if let Some(found) = deps(None, &dev) {
            rule.set("deps", found);
        }
        rules.push((Some("The doctests.".to_owned()), rule));
    }

    for bin in &package.bins {
        let name = bin.name.clone();
        claim(&name)?;
        let mut rule = Rule::new("rust_binary", &name);
        common(&mut rule);
        rule.text("crate_name", &identifier(&bin.name))
            .text("crate_root", &bin.root)
            .set("srcs", sources(bin))
            .list("visibility", vec!["//visibility:public".to_owned()]);
        rule.set(
            "rustc_env",
            Value::Map(vec![("CARGO_MANIFEST_DIR".to_owned(), package.dir.clone())]),
        );
        if package.name == "bazel-gen" {
            // `bazel run //:gazelle` reads the metadata with the toolchain's cargo.
            rule.list("data", vec!["@rules_rust//cargo:current_cargo_toolchain".to_owned()]);
            rule.set(
                "env",
                Value::Map(vec![(
                    "CARGO".to_owned(),
                    "$(rootpath @rules_rust//cargo:current_cargo_toolchain)".to_owned(),
                )]),
            );
        }
        if let Some(found) = deps(lib_dep, &normal) {
            rule.set("deps", found);
        }
        rules.push((None, rule));

        let test_name = format!("{}_bin_test", bin.name);
        claim(&test_name)?;
        let mut rule = Rule::new("rust_test", &test_name);
        common(&mut rule);
        rule.text("crate", &format!(":{name}"));
        if let Some(found) = deps(None, &dev) {
            rule.set("deps", found);
        }
        rules.push((Some(format!("The unit tests of the binary {name}.")), rule));
    }

    for test in &package.tests {
        let name = format!("{}_test", test.name);
        claim(&name)?;
        let mut rule = Rule::new("rust_test", &name);
        common(&mut rule);
        let mut data: Vec<String> = Vec::new();
        let mut extra = Vec::new();
        let mut layout = false;
        for bin in &package.bins {
            data.push(format!(":{}", bin.name));
            extra.push((
                format!("CARGO_BIN_EXE_{}", bin.name),
                format!("$(rootpath :{})", bin.name),
            ));
        }
        if package.name == "bazel-gen" && test.name == "layout" {
            data.extend(
                layout_data
                    .iter()
                    .filter(|label| !label.starts_with(&format!("//{}:", package.dir)))
                    .cloned(),
            );
            data.push(":BUILD.bazel".to_owned());
            data.push("@rules_rust//cargo:current_cargo_toolchain".to_owned());
            layout = true;
        }
        for (owner, target, label) in EXTRA_DATA {
            if *owner == package.name && *target == test.name {
                data.push((*label).to_owned());
            }
        }
        rule.text("crate_name", &identifier(&test.name))
            .text("crate_root", &test.root)
            .set("srcs", test_sources(package, test))
            .set(
                "compile_data",
                plus(Value::Raw(data_files_text.clone()), &outside_labels),
            )
            .set("rustc_env", runtime_env(extra));
        if layout {
            // The test reads the real source tree through a data file's symlink, which needs Linux.
            rule.set(
                "env",
                Value::Map(vec![(
                    "CARGO_RLOCATION".to_owned(),
                    "$(rlocationpath @rules_rust//cargo:current_cargo_toolchain)".to_owned(),
                )]),
            );
            rule.list("target_compatible_with", vec!["@platforms//os:linux".to_owned()]);
            // The gate's `stale-build: tested` input looks for this tag.
            rule.list("tags", vec!["stale-build".to_owned()]);
        }
        let labels = if data.is_empty() {
            String::new()
        } else {
            format!(" + {}", labels_at(&data, 0))
        };
        rule.set("data", Value::Raw(format!("{data_files_text}{labels}")));
        if let Some(found) = deps(lib_dep, &all) {
            rule.set("deps", found);
        }
        rules.push((None, rule));
    }

    let mut out = format!(
        "{GENERATED}\nload(\"@rules_rust//rust:defs.bzl\", {})\n\n# Read by the layout test of bazel-gen.\nexports_files({})\n",
        loads(&rules),
        labels_at(&exported_files(workspace, package), 0)
    );
    for (comment, rule) in &rules {
        out.push('\n');
        if let Some(comment) = comment {
            let _ = writeln!(out, "# {comment}");
        }
        out.push_str(&rule.render());
    }
    Ok(out)
}

/// The package's BUILD file and manifest, and the files of it that other packages include.
fn exported_files(workspace: &Workspace, package: &Package) -> Vec<String> {
    let mut names: BTreeSet<String> = ["BUILD.bazel".to_owned(), "Cargo.toml".to_owned()].into();
    for path in workspace.packages.iter().flat_map(|other| other.outside.iter()) {
        let (dir, inside) = owner(workspace, path);
        if dir == package.dir {
            names.insert(inside.to_owned());
        }
    }
    names.into_iter().collect()
}

fn loads(rules: &[(Option<String>, Rule)]) -> String {
    let kinds: BTreeSet<&str> = rules.iter().map(|(_, rule)| rule.kind).collect();
    kinds.into_iter().map(quote).collect::<Vec<_>>().join(", ")
}

fn sources(bin: &Target) -> Value {
    if bin.root.starts_with("src/") {
        glob(&["src/**/*.rs"], &[], false)
    } else {
        glob(&[bin.root.as_str()], &[], false)
    }
}

fn test_sources(package: &Package, test: &Target) -> Value {
    let mut include: Vec<&str> = vec![test.root.as_str(), "tests/*/**/*.rs"];
    if let Some(siblings) = package.test_modules.get(&test.name) {
        include.extend(siblings.iter().map(String::as_str));
    }
    glob(&include, &[], true)
}
